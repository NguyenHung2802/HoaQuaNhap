def sections(dac_diem, huong_vi, mua_vu, cach_chon, bao_quan, luu_y):
    h = []
    h.append('<h3>Đặc điểm</h3><p>%s</p>' % dac_diem)
    h.append('<h3>Hương vị</h3><p>%s</p>' % huong_vi)
    h.append('<h3>Mùa vụ</h3><p>%s</p>' % mua_vu)
    h.append('<h3>Cách chọn quả ngon</h3><ul>%s</ul>' % ''.join('<li>%s</li>' % x for x in cach_chon))
    h.append('<h3>Bảo quản</h3><p>%s</p>' % bao_quan)
    h.append('<h3>Lưu ý</h3><ul>%s</ul>' % ''.join('<li>%s</li>' % x for x in luu_y))
    return ''.join(h)

